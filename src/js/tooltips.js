//declare an event listener when the DOM content has been loaded so the Directors Office element can be resized to accommodate the tooltips (before this fix it caused a slight shift each time a tooltip is rendered and again when it disappears)
document.addEventListener('DOMContentLoaded', () => {
    const directorOfficeTable = document.getElementById('do_program_id');
	
    if (directorOfficeTable) {
        // Measure the initial computed width of the table
        const initialWidth = directorOfficeTable.offsetWidth; // Includes padding/border
		
		console.log ("the value of initialWidth is: "+initialWidth);

        // Calculate the target width (initial + the 2px shift observed)
        const targetWidth = initialWidth + 2;

		console.log ("the value of targetWidth is: "+targetWidth);

        // Apply the new width
        directorOfficeTable.style.width = `${targetWidth}px`;
    }
});



// Initialize Tippy.js for all elements with the 'person-tooltip-trigger' class
tippy('.person-tooltip-trigger', {
	interactive: true,
	allowHTML: true,
	placement: 'auto', // Or 'auto', 'bottom', etc.
	theme: 'custom-tooltip',
	// This function dynamically gets the content from the hidden div
	content(reference) {
		const person_id = reference.getAttribute('data-tooltip-id');
		const person = personnelData.find(p => p.PERS_ID === person_id);
		return generateTooltipContent(person);
	},
	delay: [100, 0],
	// Optional: A custom duration for showing/hiding
	duration: 200,
});



//function that generates the tooltip HTML for a given person in the organization so it can be displayed
function generateTooltipContent(person) {
	if (!person) {
		return '<div class="tooltip-content"><p>No information available.</p></div>';
	}

	// Helper function to escape HTML characters for safe display
	function escapeHTML(str) {
		const div = document.createElement('div');
		div.appendChild(document.createTextNode(str));
		return div.innerHTML;
	}

	// Construct the HTML string using template literals
	// Ensure dynamic content generated by the database is escaped 
	const emailHtml = person.EMAIL_ADDR ? `<p><span class="tooltip_label">Email:</span> <a href="mailto:${escapeHTML(person.EMAIL_ADDR)}">${escapeHTML(person.EMAIL_ADDR)}</a></p>` : '';
	const phoneHtml = person.WORKPH1 ? `<p><span class="tooltip_label">Phone:</span> <a href="tel:${escapeHTML(person.WORKPH1)}">${escapeHTML(person.WORKPH1)}</a></p>` : '';

	return `
		<div class="tooltip-content">
			<p class="tooltip_heading">Personnel Information</p>
			<p><span class="tooltip_label">Name:</span> ${escapeHTML(person.FIRSTNAME)} ${escapeHTML(person.LASTNAME)}</p>
			<p><span class="tooltip_label">Role:</span> ${escapeHTML(person.FULL_POSITION_NAME)}</p>
			${emailHtml}
			${phoneHtml}
		</div>
	`;

}
